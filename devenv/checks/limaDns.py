from __future__ import annotations

import sys

from devenv.lib import colima
from devenv.lib import proc
from devenv.lib_check.types import checker
from devenv.lib_check.types import fixer

tags: set[str] = {"builtin", "colima"}
name = "colima's DNS isn't working"

_DNS_CHECK = """
import socket

try:
    socket.getaddrinfo("ghcr.io", None)
except socket.gaierror as e:
    raise SystemExit(f"failed to resolve ghcr.io: {e}")
"""

_DNS_CONFIG = """
from pathlib import Path

resolv_conf = Path("/etc/resolv.conf")
print(resolv_conf.resolve())
print(resolv_conf.read_text())
"""


def _resolver_service(target: str, resolv_conf: str) -> str | None:
    if target.startswith("/run/systemd/resolve/"):
        return "systemd-resolved.service"

    nameservers = {
        line.split()[1]
        for line in resolv_conf.splitlines()
        if line.strip().startswith("nameserver ") and len(line.split()) == 2
    }
    if "127.0.0.53" in nameservers:
        return "systemd-resolved.service"
    if "# Generated by Colima" in resolv_conf and nameservers:
        return "dnsmasq.service"
    return None


@checker
def check() -> tuple[bool, str]:
    status = colima.check()
    if status != colima.ColimaStatus.UP:
        return False, "Colima isn't running."

    try:
        proc.run(
            ("colima", "exec", "--", "python3", "-Su", "-c", _DNS_CHECK),
            stdout=True,
        )
    except RuntimeError as e:
        return False, f"{e}"

    return True, ""


@fixer
def fix() -> tuple[bool, str]:
    status = colima.start()
    if status != colima.ColimaStatus.UP:
        return False, f"Colima is not healthy: {status.name.lower()}"

    try:
        config = proc.run(
            ("colima", "exec", "--", "python3", "-Su", "-c", _DNS_CONFIG),
            stdout=True,
        )
    except RuntimeError as e:
        return False, f"Unable to inspect Colima's /etc/resolv.conf: {e}"

    target, _, resolv_conf = config.partition("\n")
    service = _resolver_service(target, resolv_conf)
    if service is None:
        return (
            False,
            "Unable to identify Colima's DNS resolver from /etc/resolv.conf. "
            "Inspect the VM resolver configuration and restart the selected "
            "resolver manually.",
        )

    try:
        proc.run(
            ("colima", "exec", "--", "sudo", "systemctl", "restart", service),
            stdout=True,
        )
    except RuntimeError as e:
        print(f"""
failed to restart the vm's {service}:
{e}

we're going to try restarting colima
""")
        try:
            proc.run(
                (sys.executable, "-P", "-m", "devenv", "colima", "restart")
            )
        except RuntimeError as e:
            return False, f"{e}"

    healthy, detail = check()
    if not healthy:
        return False, f"DNS resolution is still failing after repair: {detail}"
    return True, ""
